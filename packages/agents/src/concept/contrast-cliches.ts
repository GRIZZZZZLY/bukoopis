/**
 * Противопоставления «не X, а Y» и «X, а не Y» — самый частый штамп питчей.
 * Правило в промпте их не убрало, поэтому ловим их в ответе. Граница слова —
 * через `\p{L}` с флагом `u`: `\b` в JS видит только латиницу.
 * ponytail: X и Y — до 60 знаков без конца предложения; запятые внутри X
 * разрешены, поэтому «не знал, что делать, а она ушла» тоже попадёт. Цена
 * ложного срабатывания — один лишний вызов, не порча текста.
 */
const CONTRAST_RE = new RegExp(
  [
    // не X, а Y
    String.raw`(?<!\p{L})[Нн]е(?!\p{L})[^.!?…;:\n]{1,60}?,\s*а(?!\p{L})[^.!?…;:,\n]{0,60}`,
    // X, а не Y
    String.raw`(?<!\p{L})\p{L}[^.!?…;:,\n]{0,59},\s*а\s+не(?!\p{L})[^.!?…;:,\n]{0,60}`,
  ].join("|"),
  "gu",
);

export function findContrastClichés(text: string): string[] {
  return [...text.matchAll(CONTRAST_RE)].map((m) => m[0].trim());
}
