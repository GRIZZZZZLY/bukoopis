-- Живой прогон 2026-09-22 (N1): разбор материала копил ответы
-- классификатора в памяти процесса и записывал всё только в конце прогона.
-- Падение сервера посреди разбора (он идёт минутами) обнуляло уже
-- оплаченную работу: на пробе две из трёх глав были прочитаны моделью, а в
-- базе не осталось ничего, и повтор звал модель заново.
--
-- Здесь лежит ответ классификатора по каждой единице разбора, как только он
-- получен. Ключ — книга и `intakeFileKey` (хеш имени и текста): другой текст —
-- другой ключ, поэтому устаревший ответ к изменённому файлу не приложится.
-- Строка снимается, когда прогон приземлил её и записал журнал: дальше
-- повтор отвечает журнал, а кеш нужен только до этого момента.
CREATE TABLE intake_classifications (
  book_id INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE,
  file_key TEXT NOT NULL,
  result_json TEXT NOT NULL,
  created_at TEXT NOT NULL,
  PRIMARY KEY (book_id, file_key)
);
