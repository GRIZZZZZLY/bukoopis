-- 0027_indexed_version
--
-- В3 независимого ревью 2026-09-19: поиск по прозе был заложником
-- LLM-извлекателей. Фильтр `chunks.source_id = chapters.memory_version_id`
-- показывал чанки только той версии, у которой ЗАВЕРШИЛИСЬ все четыре
-- задания коммита — три из них через модель. Недоступный бэкенд (или просто
-- упавшее извлечение) делал главу невидимой полнотекстовому поиску, который
-- от модели не зависит вовсе: индексация давно прошла, а искать нечем.
--
-- Отдельная колонка разводит два разных факта: «чанки этой версии лежат в
-- индексе» (ставит задание `index`) и «производная память этой версии
-- активирована» (ставит активация). Первого достаточно, чтобы искать.
--
-- Бэкфилл: у разобранных глав индексированная версия — та же, что
-- активированная; иначе главы, уже лежащие в индексе, пропали бы из поиска
-- до следующего коммита.
ALTER TABLE `chapters` ADD COLUMN `indexed_version_id` integer REFERENCES chapter_versions(id) ON DELETE SET NULL;--> statement-breakpoint
UPDATE `chapters` SET `indexed_version_id` = `memory_version_id` WHERE `memory_version_id` IS NOT NULL;
